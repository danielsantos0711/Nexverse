export type IconName = keyof typeof ICONS

const MENU_ONLY = new Set<string>(["house", "search", "plus", "user", "mail", "bell", "bookmark", "link", "layout-dashboard", "settings"])

/** Every icon a menu link may use, in a stable order for pickers. */
export const ICON_NAMES = Object.keys(ICONS) as IconName[]
/** The icons a forum category may use (the database's allow-list). */
export const CATEGORY_ICON_NAMES = ICON_NAMES.filter((n) => !MENU_ONLY.has(n))

export const isIconName = (s: string): s is IconName => s in ICONS
export const iconFor = (name: string | undefined, fallback: LucideIcon = MessagesSquareIcon): LucideIcon => (name && isIconName(name) ? ICONS[name] : fallback)

/** An icon by name, decorative (a label always sits next to it). */
export function NamedIcon({ name, className }: { name: string | undefined; className?: string }) {
  return createElement(iconFor(name), { "aria-hidden": true, className })
}
