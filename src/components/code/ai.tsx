"use client"

import { useState } from "react"
import { LoaderCircleIcon, SparklesIcon, XIcon } from "lucide-react"
import { Button } from "@/components/ui/button"
import { useAiStatus } from "@/lib/ai-client"
import { explainFile, summariseRepo, type ExplainFile, type RepoSummary } from "@/lib/code/ai"
import { useSession } from "@/lib/store"
import { Copy } from "@/components/content/copy"

/*
 * Free AI on code pages (job "code"). Nothing renders when AI is off for this site or for the code job, so there
 * is never a button that cannot work. Answers are labelled as AI and stay in this page only.
 */

function useCodeAi() {
  const status = useAiStatus()
  const session = useSession()
  return status.ready && status.enabled && status.jobs.code !== false && Boolean(session.user)
}

const AiMark = ({ model }: { model: string }) => <p className="text-[11px] text-muted-foreground">AI-generated by {model || "a free model"}. It can be wrong: check it against the code.</p>

export function RepoSummaryCard({ repo, description, readme, files }: { repo: string; description: string; readme: string; files: string[] }) {
  const on = useCodeAi()
  const [busy, setBusy] = useState(false)
  const [result, setResult] = useState<{ data: RepoSummary; model: string } | null>(null)
  const [error, setError] = useState<string | null>(null)
  if (!on || (!readme && !files.length)) return null
  const run = async () => {
    setBusy(true)
    setError(null)
    try {
      const r = await summariseRepo({ repo, description, readme, files })
      setResult({ data: r.data, model: r.model })
    } catch (err) {
      setError((err as Error).message)
    } finally {
      setBusy(false)
    }
  }
  return (
    <section className="relative overflow-hidden rounded-xl bg-card p-4">
      <h2 className="flex items-center gap-2 text-sm font-medium">
        <SparklesIcon aria-hidden className="size-4 text-ion" /> <Copy k="code-repo.ai.ai-summary">AI summary</Copy>
      </h2>
      {result ? (
        <div className="mt-2 flex flex-col gap-2 text-sm motion-safe:animate-in motion-safe:fade-in">
          <p className="text-foreground/90">{result.data.summary}</p>
          {result.data.highlights.length > 0 && (
            <ul className="list-disc space-y-0.5 pl-5 text-muted-foreground">
              {result.data.highlights.map((h) => (
                <li key={h}>{h}</li>
              ))}
            </ul>
          )}
          {result.data.audience && <p className="text-muted-foreground">For: {result.data.audience}</p>}
          {result.data.stack.length > 0 && (
            <ul className="flex flex-wrap gap-1.5" aria-label="Stack">
              {result.data.stack.map((s) => (
                <li key={s} className="rounded-full bg-secondary px-2 py-0.5 text-xs">
                  {s}
                </li>
              ))}
            </ul>
          )}
          <AiMark model={result.model} />
        </div>
      ) : (
        <>
          <p className="mt-1 text-sm text-muted-foreground"><Copy k="code-repo.ai.what-this-repository-does-and">What this repository does and who it is for, from its README and files.</Copy></p>
          {error && (
            <p role="alert" className="mt-2 text-sm text-destructive">
              {error}
            </p>
          )}
          <Button size="sm" variant="outline" className="mt-3" onClick={run} disabled={busy}>
            {busy ? <LoaderCircleIcon aria-hidden className="animate-spin" /> : <SparklesIcon aria-hidden />}
            {busy ? "Reading…" : "Summarise"}
          </Button>
        </>
      )}
    </section>
  )
}

export function ExplainButton({ onClick, busy }: { onClick: () => void; busy: boolean }) {
  const on = useCodeAi()
  if (!on) return null
  return (
    <Button size="sm" variant="outline" className="h-7 rounded-full" onClick={onClick} disabled={busy}>
      {busy ? <LoaderCircleIcon aria-hidden className="animate-spin" /> : <SparklesIcon aria-hidden className="text-ion" />}
      Explain this file
    </Button>
  )
}

/** "Explain this file": a panel above the code with a summary, the main parts and notes. */
export function useExplain(repo: string, path: string, text: string | null) {
  const [busy, setBusy] = useState(false)
  const [result, setResult] = useState<{ data: ExplainFile; model: string } | null>(null)
  const [error, setError] = useState<string | null>(null)
  const run = async () => {
    if (!text) return
    setBusy(true)
    setError(null)
    try {
      const r = await explainFile({ repo, path, text })
      setResult({ data: r.data, model: r.model })
    } catch (err) {
      setError((err as Error).message)
    } finally {
      setBusy(false)
    }
  }
  const panel =
    result || error ? (
      <section className="relative border-b border-border bg-card p-4 text-sm motion-safe:animate-in motion-safe:fade-in motion-safe:slide-in-from-top-1" aria-live="polite">
        <button
          onClick={() => {
            setResult(null)
            setError(null)
          }}
          className="absolute top-3 right-3 grid size-7 place-items-center rounded-full text-muted-foreground hover:bg-secondary hover:text-foreground"
          aria-label="Close the explanation"
        >
          <XIcon aria-hidden className="size-4" />
        </button>
        <h2 className="mb-2 flex items-center gap-2 font-medium">
          <SparklesIcon aria-hidden className="size-4 text-ion" /> <Copy k="code-repo.ai.what-this-file-does">What this file does</Copy>
        </h2>
        {error ? (
          <p role="alert" className="text-destructive">
            {error}
          </p>
        ) : (
          result && (
            <div className="flex max-w-3xl flex-col gap-3">
              <p className="text-foreground/90">{result.data.summary}</p>
              {result.data.parts.length > 0 && (
                <dl className="grid gap-1.5 sm:grid-cols-[minmax(0,14rem)_1fr]">
                  {result.data.parts.map((p) => (
                    <div key={p.name} className="contents">
                      <dt className="truncate font-mono text-[13px] text-ion">{p.name}</dt>
                      <dd className="text-muted-foreground">{p.what}</dd>
                    </div>
                  ))}
                </dl>
              )}
              {result.data.notes.length > 0 && (
                <ul className="list-disc space-y-0.5 pl-5 text-muted-foreground">
                  {result.data.notes.map((n) => (
                    <li key={n}>{n}</li>
                  ))}
                </ul>
              )}
              <AiMark model={result.model} />
            </div>
          )
        )}
      </section>
    ) : null
  return { run, busy, panel }
}
